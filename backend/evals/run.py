"""Run every eval suite and write docs/evals.md + evals/results.json.

    python -m evals.run            # full
    python -m evals.run --quick    # smaller samples
    python -m evals.run verdicts twin   # just some suites
"""

import importlib
import json
import sys
import time
from pathlib import Path

from evals.core import SuiteResult, fmt

SUITES = ["verdicts"]
ROOT = Path(__file__).resolve().parents[2]


def main() -> int:
    quick = "--quick" in sys.argv
    wanted = [a for a in sys.argv[1:] if not a.startswith("--")] or SUITES
    results: list[SuiteResult] = []
    for name in wanted:
        module = importlib.import_module(f"evals.{name}")
        result = module.run(quick)
        results.append(result)
        mark = "PASS" if result.passed else "FAIL"
        print(f"\n[{mark}] {result.name}: {result.description} ({result.seconds:.1f}s)")
        for m in result.metrics:
            op = ">=" if m.higher_is_better else "<="
            print(f"   {'ok ' if m.passed else 'XX '} {m.name:<44} {fmt(m.value, m.unit):>10}  (target {op} {fmt(m.target, m.unit)})")
    if set(wanted) == set(SUITES) and not quick:
        write(results)
    return 0 if all(r.passed for r in results) else 1


def write(results: list[SuiteResult]) -> None:
    data = [{"name": r.name, "description": r.description, "seconds": round(r.seconds, 1), "passed": r.passed,
             "metrics": [m.to_dict() for m in r.metrics], "details": r.details} for r in results]
    (ROOT / "backend/evals/results.json").write_text(json.dumps({"generated": int(time.time()), "suites": data}, indent=1))
    lines = [
        "# Evals",
        "",
        "Generated by `cd backend && .venv/bin/python -m evals.run`. Each suite checks one part of the system",
        "against a target; the targets are what we consider good enough to demo and to trust.",
        "",
        f"**{sum(r.passed for r in results)} of {len(results)} suites pass.**",
        "",
    ]
    for r in results:
        lines += [f"## {r.name} {'✅' if r.passed else '❌'}", "", r.description, "", "| Metric | Value | Target | |", "| --- | --- | --- | --- |"]
        for m in r.metrics:
            op = "≥" if m.higher_is_better else "≤"
            note = f" {m.note}" if m.note else ""
            lines.append(f"| {m.name}{' ·' + note if note else ''} | {fmt(m.value, m.unit)} | {op} {fmt(m.target, m.unit)} | {'✅' if m.passed else '❌'} |")
        lines.append("")
    (ROOT / "docs/evals.md").write_text("\n".join(lines))


if __name__ == "__main__":
    sys.exit(main())
